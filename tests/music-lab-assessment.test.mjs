import assert from 'node:assert/strict';
import {LabAssessment,labMidiEvent} from '../web/music-lab-assessment.js';
import {lessonGroups,transposeLesson} from '../web/music-lab-model.js';
import {LabProgress,PROGRESS_KEY,readLabProgress} from '../web/music-lab-progress.js';
import scale from '../web/music-lab/scale-c-major-rh-1oct.json' with {type:'json'};
import chord from '../web/music-lab/chord-c-major-rh.json' with {type:'json'};

const event=(data,timeStamp)=>labMidiEvent({data,timeStamp});
const assess=(lesson,channel=null)=>new LabAssessment(lessonGroups(lesson.notes),{channel,bpm:60,ppq:480,chordWindowMs:120});
const send=(lab,time,st,pitch,value=100)=>lab.input(event([st,pitch,value],time));
assert.equal(event([0x90,60,0],1).type,'off');
assert.equal(event([0x8f,60,64],2).channel,15);
assert.equal(event([0xb0,64,63],3).down,false);
assert.equal(event([0xb0,64,64],4).down,true);
assert.equal(event([0xb7,120,0],5).type,'reset');
assert.equal(event([0xbf,123,0],5).type,'reset');
assert.equal(event([0x90,128,10],6),null);
assert.equal(event([0x90,60,10.5],7),null);
assert.equal(event([0xf0,60,80],8),null);
assert.equal(event([0x90,60,80],undefined).at,null);

const played=assess(scale);
assert.equal(send(played,0,0x80,60,0),null,'a release before the first attack chooses no channel');
assert.equal(send(played,1,0x92,61).kind,'extra');
assert.equal(played.index,0);
assert.equal(played.channel,2);
assert.equal(send(played,5,0x91,60),null);
assert.equal(send(played,10,0x92,60).kind,'match');
assert.equal(send(played,20,0xb2,64,127).kind,'pedal');
assert.equal(send(played,30,0xb1,123,0),null);
assert.equal(send(played,50,0x91,60,0),null);
assert.deepEqual(send(played,260,0x92,60,0),{kind:'release',pitch:60,ms:250,reference:1000});
assert.equal(played.pedals.get(2),true,'sustain stays down after measuring physical key duration');
assert.equal(send(played,300,0x92,62).kind,'match');
assert.equal(send(played,310,0x92,62).kind,'extra','another attack cannot satisfy the same target');
assert.equal(send(played,400,0x82,62,0).ms,undefined,'the overwritten hold has no invented release');
assert.equal(send(played,404,0xb2,120,0).kind,'reset');
assert.equal(played.held.size,0);
assert.equal(played.pedals.size,0);
assert.equal(played.index,2);
played.resume(null);
assert.equal(send(played,410,0x9f,64).kind,'match');
assert.equal(played.summary().missing,12);
assert.equal(played.summary().holdMeanMs,250);

const harmony=assess(chord,0);
assert.equal(send(harmony,0,0x90,60).kind,'partial');
assert.equal(send(harmony,30,0x90,64).kind,'partial');
assert.equal(send(harmony,121,0x90,67).kind,'wide');
assert.equal(harmony.summary().matched,0);
for(const pitch of [60,64,67])send(harmony,130,0x80,pitch,0);
assert.equal(send(harmony,150,0x90,61).kind,'extra');
assert.equal(send(harmony,153,0x90,60).kind,'retry');
for(const pitch of [61,60])send(harmony,170,0x80,pitch,0);
assert.equal(send(harmony,200,0x90,67).kind,'partial');
assert.equal(send(harmony,260,0x90,60).kind,'partial');
assert.equal(send(harmony,320,0x90,64).kind,'match','the window includes its boundary');
assert(!harmony.complete);
assert.equal(send(harmony,400,0x90,64),null,'retrigger after completion does not claim another hit');
for(const pitch of [60,64,67])send(harmony,500,0x90,pitch,0);
assert(harmony.complete);
assert.deepEqual(harmony.summary(),{expected:1,matched:1,missing:0,extras:1,retries:1,holdSamples:2,holdMeanMs:270,windowUnavailable:false});

const unknown=assess(chord,0);
for(const pitch of [60,64,67])send(unknown,undefined,0x90,pitch);
assert.equal(unknown.summary().matched,1);
assert.equal(unknown.summary().windowUnavailable,true);

const solo=assess(transposeLesson(scale,'F'),0);
assert.equal(send(solo,0,0x90,65).kind,'match');
const memory=new Map();
const storage={getItem:key=>memory.get(key),setItem:(key,value)=>memory.set(key,value)};
const progress=new LabProgress(storage);
assert.equal(progress.record(chord,harmony.summary()),true);
for(let i=0;i<10;i++)progress.record(scale,played.summary());
const restored=new LabProgress(storage);
assert.equal(restored.get(scale).attempts,10);
assert.equal(restored.get(scale).history.length,8);
assert.equal(restored.get(chord).history[0].summary.holdSamples,2);
assert.equal(restored.get(transposeLesson(scale,'F')),undefined);
assert.deepEqual([...memory.keys()],[PROGRESS_KEY]);
assert.equal(memory.get(PROGRESS_KEY).includes('device'),false);
assert.equal(memory.get(PROGRESS_KEY).includes('pitch'),false);
storage.setItem(PROGRESS_KEY,'{invalid');
assert.equal(readLabProgress(storage).size,0);
const denied=new LabProgress({getItem(){throw Error();},setItem(){throw Error();}});
assert.equal(denied.record(chord,harmony.summary()),false);
assert.equal(denied.record(chord,harmony.summary()),false);
assert.equal(denied.get(chord).attempts,2);
console.log('PASS Music Lab W2: MIDI normalization, channel isolation, pitch matching, chord window, physical hold and pedal, reconnect and bounded progress');
