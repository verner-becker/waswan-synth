import assert from 'node:assert/strict';
import {emptyProject,makeTrack,uuid,clipSeconds,validateProject} from '../web/daw-project.js';
import {ProjectController} from '../web/daw-controller.js';
import {wavHeader} from '../web/studio-format.js';
const c=new ProjectController();
for(let i=0;i<8;i++)c.command('track.create',makeTrack('midi','Instrument '+i));
assert.equal(c.snapshot().tracks.length,8,'logical tracks do not alias four firmware parts');
const original=c.snapshot(),revision=c.revision;
assert.throws(()=>c.execute({id:'stale',projectId:original.id,expectedRevision:0,type:'project.update',payload:{name:'Lost update'}}),/refresh/);
assert.deepEqual(c.snapshot(),original);
const command={id:'repeat',projectId:original.id,expectedRevision:revision,type:'project.update',payload:{name:'Changed'}};
const result=c.execute(command);assert.deepEqual(c.execute(command),result);assert.equal(c.revision,revision+1);
assert.throws(()=>c.execute({...command,payload:{name:'Other'}}),/different data/);
assert.throws(()=>c.execute({...command,projectId:'previous-project'}),/different project/);
const before=c.snapshot();
assert.throws(()=>c.command('batch',{commands:[{type:'project.update',payload:{name:'Partial'}},{type:'track.update',payload:{id:before.tracks[0].id,changes:{volume:-1}}}]}));
assert.deepEqual(c.snapshot(),before,'invalid batch must not commit its first edit');
const t=makeTrack('audio','Source');c.command('track.create',t);
const source=new Blob([wavHeader(128),Int16Array.from({length:256},(_,i)=>i*10)]),meta={id:uuid(),name:'Original',sampleRate:44100,channels:2,frames:128,bytes:source.size};c.addAsset(meta,source);
const clip={id:uuid(),type:'audio',trackId:t.id,name:'Audio',assetId:meta.id,position:{unit:'seconds',value:2},offset:0,frames:128,gain:1,pan:0,fadeIn:0,fadeOut:0};c.command('clip.add',clip);
const saved=c.snapshot();c.markSaved(saved);assert(!c.dirty);
c.command('batch',{commands:[{type:'clip.remove',payload:{id:clip.id}},{type:'asset.remove',payload:{id:meta.id}}]});
assert(c.assets.has(meta.id),'Undo owns the original bytes even after removing the source');
c.command('undo');assert.deepEqual(c.snapshot(),saved);assert(!c.dirty);assert.deepEqual(await c.assets.get(meta.id).arrayBuffer(),await source.arrayBuffer());
c.command('redo');assert(c.dirty);c.command('undo');c.command('project.update',{bpm:100});assert(!c.canRedo);
assert.equal(clipSeconds(c.snapshot().clips[0],100),2,'absolute anchor does not move with BPM');
assert.equal(clipSeconds({position:{unit:'ticks',value:960}},100),.6);
c.markSaved(saved);assert(c.dirty,'finishing an older save does not clear newer edits');
c.command('batch',{commands:[{type:'clip.remove',payload:{id:clip.id}},{type:'asset.remove',payload:{id:meta.id}}]});c.clearHistory();assert(!c.assets.has(meta.id),'collect only after history releases the source');
const exposed=c.snapshot();exposed.name='Mutated outside controller';assert.notEqual(c.snapshot().name,exposed.name);
assert.throws(()=>validateProject({...emptyProject(),tracks:Array.from({length:33},()=>makeTrack('audio'))}));
const gesture=new ProjectController(),initial=gesture.snapshot();
for(const volume of [.9,.8,.7])gesture.command('master.update',{volume},{mergeKey:'master:volume'});
gesture.command('undo');assert.deepEqual(gesture.snapshot(),initial,'one slider gesture is one Undo');
gesture.command('redo');assert.equal(gesture.snapshot().master.volume,.7);
gesture.endCoalescing();gesture.command('master.update',{volume:.6},{mergeKey:'master:volume'});gesture.command('undo');assert.equal(gesture.snapshot().master.volume,.7,'separate gestures retain separate history');
assert.throws(()=>gesture.command('master.update',{volume:1},{mergeKey:{}}),/gesture/);
console.log('PASS DAW project: >4 logical tracks, revision conflicts, idempotence, atomic batches, byte-owning Undo/Redo, anchors, dirty/save races, asset collection');
