import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from '../../.tools/browser/node_modules/playwright/index.mjs';

const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome'});
try {
  const page=await browser.newPage({viewport:{width:1000,height:850}});
  await page.goto(new URL('sampler-wav.js',process.env.SAMPLER_BROWSER_URL||'http://localhost:8737/simulator/').href);
  await page.setContent('<link rel="stylesheet" href="ui-foundation.css"><main class="ww-page ww-shell ww-sampler-studio"></main>');
  const crossing=await page.evaluate(async()=>{
    const {createSamplerWaveform}=await import('./ui-sampler-waveform.js');
    const {nearestZeroCrossing}=await import('./ui-sampler-wave-tools.js');
    const {inspectWav}=await import('./sampler-wav.js');
    const {encodeSample}=await import('./sampler-offline.js');
    const rate=48000, frames=rate*3;
    const pcm=new Float32Array(frames*2);
    for(let frame=0;frame<frames;frame++){
      const phase=frame%rate;
      pcm[frame*2]=phase>1500&&phase<12000?.3*Math.sin(2*Math.PI*200*frame/rate):0;
      pcm[frame*2+1]=phase>24000&&phase<36000?.4*Math.sin(2*Math.PI*251*frame/rate):0;
    }
    const file=new File([encodeSample({channels:2,sampleRate:rate,pcm})],'Three beats.wav');
    const context=new AudioContext(), gain=context.createGain();gain.connect(context.destination);
    const media=context.createMediaElementSource.bind(context);
    context.createMediaElementSource=el=>{window.stream=el;return media(el);};
    window.markerEdits=[];
    window.originalFile=file;
    window.wave=createSamplerWaveform({getAudio:()=>({context,gain}),onMarkers:({markers})=>markerEdits.push(markers),
      onSlices:({file,markers})=>{window.kit={name:file.name,markers};},
      onLoop:({file,...range})=>{window.loop={name:file.name,...range};}});
    document.querySelector('main').append(wave.node);
    await wave.open(file,{markers:[48000]});
    return nearestZeroCrossing(file,await inspectWav(file,{anyRate:true}),2500);
  });
  assert(Math.abs(crossing-2520)<=1);
  const button=text=>page.getByRole('button',{name:text,exact:true}), field=text=>page.getByLabel(text,{exact:true});
  const set=async(name,value)=>{const box=field(name);await box.fill(String(value));await box.press('Tab');};
  await page.locator('.ww-wave-tools summary').click();
  assert.equal(await field('Waveform slice markers').inputValue(),'48000');
  assert.equal(await page.evaluate(()=>markerEdits.length),0);
  const canvas=page.locator('.ww-sampler-waveform canvas');
  await canvas.scrollIntoViewIfNeeded();
  let rect=await canvas.boundingBox();
  await field('Snap pointer').selectOption('beat');
  await page.mouse.click(rect.x+rect.width*.46,rect.y+rect.height*.5);
  assert.equal(await field('Cursor (frame)').inputValue(),'72000');
  assert.deepEqual(await page.evaluate(()=>wave.getSelection()),{start:0,end:144000,sampleRate:48000});
  await canvas.focus();await canvas.press('Shift+ArrowRight');
  assert.equal(await field('Cursor (frame)').inputValue(),'72001');
  await button('Set start at cursor').click();
  assert.equal(await field('Start frame').inputValue(),'72001');
  await set('Start frame',0);
  await button('Zoom in').click();
  await page.waitForFunction(()=>!document.querySelector('.ww-sampler-waveform canvas').hasAttribute('aria-busy'));
  assert(await button('Fit file').isEnabled());
  await button('Amplitude +').click();
  assert(await page.getByText('Amplitude 2×',{exact:true}).isVisible());
  await button('Fit amplitude').click();await button('Scroll right').click();
  await button('Fit file').click();
  await set('End frame',48000);
  await field('Snap pointer').selectOption('off');
  await canvas.scrollIntoViewIfNeeded();
  rect=await canvas.boundingBox();
  await page.mouse.move(rect.x+rect.width/3,rect.y+rect.height*.5);
  await page.mouse.down();
  await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.5);
  await page.mouse.up();
  assert.equal(await field('Start frame').inputValue(),'0');
  assert(Math.abs(Number(await field('End frame').inputValue())-72000)<220);
  await set('End frame',48000);
  await button('Slice selection by grid').click();
  assert.deepEqual(await page.evaluate(()=>wave.getMarkers()),[24000]);
  await button('Find transients in selection').click();
  await page.waitForFunction(()=>wave.getMarkers().length===2);
  const attacks=await page.evaluate(()=>wave.getMarkers());
  assert(attacks[0]>=1500&&attacks[0]<1700&&attacks[1]>=24000&&attacks[1]<24200);
  await set('Cursor (frame)',32000);await button('Add slice at cursor').click();
  await button('Use slices in kit builder').click();
  assert.deepEqual(await page.evaluate(()=>kit),{name:'Three beats.wav',markers:[...attacks,32000]});
  await button('Remove nearest slice').click();
  assert.deepEqual(await page.evaluate(()=>wave.getMarkers()),attacks);
  await set('Waveform slice markers','120, 220, 320');
  assert.equal(await page.evaluate(()=>markerEdits.length),5);
  await set('Start frame',2000);await set('End frame',10550);
  await button('Suggest loop points').click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Suggested loop points"]').options.length===5);
  assert.equal(await field('Start frame').inputValue(),'2000');
  assert.equal(await field('End frame').inputValue(),'10550');
  assert.equal(await page.evaluate(()=>window.loop),undefined);
  await button('Use suggested points').click();
  assert.deepEqual(await page.evaluate(()=>wave.getSelection()),{start:2032,end:10432,sampleRate:48000});
  assert.equal(await page.evaluate(()=>window.loop),undefined);
  await set('End frame',20000);await set('Start frame',12500);
  await button('Suggest loop points').click();
  await page.getByText('No loop points found.',{exact:false}).waitFor();
  assert(await button('Use suggested points').isDisabled());
  await set('Start frame',0);await set('End frame',48000);
  await field('Region loop mode').selectOption('pingPong');
  await set('Region loop crossfade (frames)',120);
  await button('Use selection as region loop').click();
  assert.deepEqual(await page.evaluate(()=>loop),{name:'Three beats.wav',start:0,end:48000,mode:'pingPong',crossfade:120});
  await button('Repeat selection').click();
  await page.getByText('Repeating selection.',{exact:true}).waitFor();
  assert(await page.evaluate(()=>stream.loop&&!stream.paused));
  await page.evaluate(()=>wave.open(new File([originalFile],'Checkpoint.wav'),{markers:[120,220,320],
    loop:{start:0,end:48000,mode:'pingPong',crossfade:120}}));
  assert.equal(await page.evaluate(()=>markerEdits.length),5,'opening an existing state does not edit its markers');
  assert(await page.evaluate(()=>stream.loop&&!stream.paused),'changing visual comparison preserves the active preview');
  assert.equal(await field('Region loop mode').inputValue(),'pingPong');
  await button('Stop preview').click();
  await set('Cursor (frame)',96000);await button('Preview from cursor').click();
  await page.waitForFunction(()=>!stream.paused&&stream.duration===1);
  assert(!await page.evaluate(()=>stream.loop));
  await button('Stop preview').click();
  await mkdir('.local/validation/sampler-ux-5',{recursive:true});
  await page.locator('main').screenshot({path:'.local/validation/sampler-ux-5/wave-tools.png'});
  console.log('PASS zero crossing, beat snap, click cursor without changing selection, frame nudge, selection handles, zoom/fit and scroll, PCM attack/beat/manual slices, five sine seam candidates with absolute frames, silent seam rejection, kit and explicit loop handoff, loop/stop and cursor playback');
}finally{await browser.close();}
