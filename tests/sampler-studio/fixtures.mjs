export function pcmWav(samples, {channels = 2, sampleRate = 44100, junk = false} = {}) {
  const bytes = new Uint8Array(samples.length * 2 + 44 + (junk ? 12 : 0));
  const view = new DataView(bytes.buffer);
  const text = (offset, value) => bytes.set(new TextEncoder().encode(value), offset);
  text(0, 'RIFF');
  view.setUint32(4, bytes.length - 8, true);
  text(8, 'WAVEfmt ');
  view.setUint32(16, 16, true);
  view.setUint16(20, 1, true);
  view.setUint16(22, channels, true);
  view.setUint32(24, sampleRate, true);
  view.setUint32(28, sampleRate * channels * 2, true);
  view.setUint16(32, channels * 2, true);
  view.setUint16(34, 16, true);
  let data = 36;
  if (junk) {
    text(data, 'JUNK');
    view.setUint32(data + 4, 3, true);
    bytes.set([5, 6, 7, 0], data + 8);
    data += 12;
  }
  text(data, 'data');
  view.setUint32(data + 4, samples.length * 2, true);
  samples.forEach((value, index) => view.setInt16(data + 8 + index * 2, value, true));
  return bytes;
}

function pianoWav(note, strength, take, release = false) {
  const frameCount = release ? 5512 : 15435;
  const frequency = 440 * 2 ** ((note - 69) / 12);
  const pcm = new Int16Array(frameCount * 2);
  for (let frame = 0; frame < frameCount; frame++) {
    const time = frame / 44100;
    const phase = Math.PI * 2 * frequency * time;
    const envelope = (1 - Math.exp(-time * 900)) * Math.exp(-time * (release ? 42 : 6)) *
      Math.min(1, (frameCount - frame - 1) / 200);
    const overtones = strength * Math.sin(2 * phase + take * .1) + .13 * take * Math.sin(3 * phase);
    pcm[frame * 2] = (Math.sin(phase) + overtones) * envelope * 12000;
    pcm[frame * 2 + 1] = (Math.sin(phase + .2) + overtones * .8) * envelope * 10000;
  }
  return pcmWav(pcm);
}

export async function createSamplerFixtures(root) {
  await initializeLibrary(root, {id: 'waswan-sampler-fixtures', name: 'WASWAN sampler fixtures'});
  const provenance = {method: 'Deterministic synthetic signals generated by tests/sampler-studio/fixtures.mjs'};
  const store = (id, bytes) => importOriginal(root, bytes, `Samples/Originals/WASWAN fixtures/${id}.wav`,
    {id, provenance, license: 'GPL-3.0-only'});
  const pulse = await store('stereo-pulse', pcmWav(Int16Array.from({length: 128},
    (_, index) => index === 0 ? 12000 : index === 5 ? -9000 : 0), {junk: true}));
  const single = await publish(root, createInstrument({
    id: 'stereo-pulse', name: 'Stereo pulse', tags: ['Fixture'], samples: [pulse],
    regions: [{id: 'pulse', sample: pulse.id, group: 'main', root: 60, mode: 'oneShot'}],
  }), {path: 'Instruments/Fixtures/Stereo pulse', expectedRevision: 0});

  const samples = [], regions = [], variations = [];
  for (const [note, key] of [[48, [36, 53]], [60, [54, 65]], [72, [66, 84]]]) {
    for (const [layer, strength] of [['soft', 0.2], ['hard', 0.65]]) {
      const set = `${layer}-${note}`;
      variations.push({id: set, mode: 'sequential', order: ['a', 'b']});
      for (const [member, take] of [['a', 0], ['b', 1]]) {
        const sample = await store(`${set}-${member}`, pianoWav(note, strength, take));
        samples.push(sample);
        regions.push({id: sample.id, sample: sample.id, group: 'felt', root: note, key, layer,
          articulation: 'felt', variation: {set, member}});
      }
    }
    const sample = await store(`bright-${note}`, pianoWav(note, .85, 2));
    samples.push(sample);
    regions.push({id: sample.id, sample: sample.id, group: 'bright', root: note, key, articulation: 'bright'});
  }
  const tail = await store('felt-release', pianoWav(60, .65, 1, true));
  samples.push(tail);
  regions.push({id: 'felt-release', sample: tail.id, group: 'felt', root: 60, key: [36, 84],
    articulation: 'felt', trigger: 'release', mode: 'oneShot'});
  const piano = await publish(root, createInstrument({
    id: 'fixture-piano', name: 'Fixture piano', tags: ['Fixture', 'Piano'], samples, regions, variations,
    initialArticulation: 'felt',
    groups: [{id: 'felt'}, {id: 'bright'}],
    articulations: [
      {id: 'felt', selectorGroup: 'style', select: {keyswitch: 24}},
      {id: 'bright', selectorGroup: 'style', select: {keyswitch: 25}},
    ],
    layers: [
      {id: 'soft', velocity: [1, 80], fadeOut: [64, 80]},
      {id: 'hard', velocity: [64, 127], fadeIn: [64, 80]},
    ],
  }), {path: 'Instruments/Fixtures/Fixture piano', expectedRevision: 0});
  return {single, piano};
}

